import { spawnSync } from "node:child_process";
import { copyFile, mkdir, mkdtemp, readFile, readdir, rm, stat, utimes, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { LIBRARY_PROGRAM_FILES as COLLECTION_PROGRAM_FILES, LIBRARY_PROGRAM_IDS as COLLECTION_PROGRAM_IDS } from "../shared/wls-library-catalogue";

const workspace = fileURLToPath(new URL("../", import.meta.url));
const tsx = resolve(workspace, "node_modules/tsx/dist/cli.mjs");
const artifact = "shared/wls-library-sources.generated.ts";
const runtimeFiles = [
  "scripts/generate-wls-library.ts",
  "scripts/wls-library-artifact.ts",
  "shared/wls-library-catalogue.ts",
  "shared/wls-library-compiler.ts",
  "shared/wls-collection-vm.ts",
  "shared/wls-map-vm.ts",
  "shared/wls-execution.ts",
  "shared/wnsp-model.ts",
];
let root: string;
let sources: Record<string, string>;

async function put(path: string, contents: string) {
  const target = join(root, path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, contents, "utf8");
}

// Independent fixture serialization: setup never runs the generator in write mode.
async function putArtifact() {
  await put(artifact,
    "// Generated by npm run generate:wls-library. DO NOT EDIT.\n" +
    "// Canonical programs: shared/wls-library/**/*.wls\n" +
    `export const COLLECTION_LIBRARY_SOURCES = Object.freeze(${JSON.stringify(sources, null, 2)} as const);\n`);
}

async function snapshot(directory = root): Promise<unknown[]> {
  const entries: unknown[] = [];
  for (const name of (await readdir(directory)).sort()) {
    const path = join(directory, name);
    const info = await stat(path);
    entries.push(info.isDirectory()
      ? [name, "directory", info.mode, await snapshot(path)]
      : [name, "file", info.mode, info.mtimeMs, (await readFile(path)).toString("hex")]);
  }
  return entries;
}

async function checkWithoutWrites() {
  // Backdate every file so even a same-content rewrite is observable.
  async function backdate(directory: string): Promise<void> {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await backdate(path);
      else await utimes(path, new Date("2000-01-01"), new Date("2000-01-01"));
    }
  }
  await backdate(root);
  const before = await snapshot();
  const result = spawnSync(process.execPath, [tsx, join(root, "scripts/generate-wls-library.ts"), "--check"], {
    cwd: root,
    encoding: "utf8",
    timeout: 10_000,
    maxBuffer: 256_000,
    // Do not inherit database credentials, provider keys or Node preload hooks.
    env: { PATH: process.env.PATH, TSX_DISABLE_CACHE: "1" },
  });
  expect(await snapshot()).toEqual(before);
  expect(result.error).toBeUndefined();
  expect(result.signal).toBeNull();
  return result;
}

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "wls-library-check-"));
  await put("package.json", '{"type":"module"}\n');
  for (const path of runtimeFiles) {
    await mkdir(dirname(join(root, path)), { recursive: true });
    await copyFile(join(workspace, path), join(root, path));
  }
  sources = {};
  for (const id of COLLECTION_PROGRAM_IDS) {
    sources[id] = `WLS-COLLECTION/1\n// synthetic ${id}: Ψ🌊\nCONST ["value",1]\nRETURN ["value"]\n`;
    await put(`shared/wls-library/${COLLECTION_PROGRAM_FILES[id]}`, sources[id]);
  }
  await putArtifact();
  await put("unrelated/sentinel.bin", "untouched fixture data\0Ψ\n");
});

afterEach(async () => {
  if (root) await rm(root, { recursive: true, force: true });
});

describe("WLS library release check in an isolated source tree", () => {
  it("rebuilds a missing artifact without importing runtime-generated sources", async () => {
    await rm(join(root, artifact));
    const result = spawnSync(process.execPath, [tsx, join(root, "scripts/generate-wls-library.ts")], {
      cwd: root, encoding: "utf8", timeout: 10_000, maxBuffer: 256_000,
      env: { PATH: process.env.PATH, TSX_DISABLE_CACHE: "1" },
    });
    expect(result.status).toBe(0);
    expect(result.stderr).toBe("");
    expect(result.stdout).toBe("Generated WLS library artifact from canonical programs.\n");
    const generated = await readFile(join(root, artifact), "utf8");
    expect(generated).toContain(JSON.stringify(sources["string.contains"]));
    expect((await checkWithoutWrites()).status).toBe(0);
  });
  it("succeeds for synchronized valid sources without writing any files", async () => {
    const result = await checkWithoutWrites();
    expect(result.status).toBe(0);
    expect(result.stdout).toBe("WLS library artifact matches all canonical programs.\n");
    expect(result.stderr).toBe("");
  });

  it("rejects a stale artifact without repairing it", async () => {
    await put(artifact, "// stale fixture artifact\n");
    const result = await checkWithoutWrites();
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("WLS library artifact is stale. Run npm run generate:wls-library.");
  });

  it("rejects a valid source change even when the artifact still contains all catalogue programs", async () => {
    await put(`shared/wls-library/${COLLECTION_PROGRAM_FILES["recipient.at"]}`,
      sources["recipient.at"].replace('["value",1]', '["value",2]'));
    const result = await checkWithoutWrites();
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("WLS library artifact is stale.");
  });

  it("rejects a missing artifact without creating it", async () => {
    await rm(join(root, artifact));
    const result = await checkWithoutWrites();
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("ENOENT");
    expect(result.stderr).toContain("wls-library-sources.generated.ts");
  });

  it.each(COLLECTION_PROGRAM_IDS)("rejects missing canonical source %s without restoring it", async id => {
    await rm(join(root, "shared/wls-library", COLLECTION_PROGRAM_FILES[id]));
    const result = await checkWithoutWrites();
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("ENOENT");
    expect(result.stderr).toContain(COLLECTION_PROGRAM_FILES[id]);
  });

  it.each(COLLECTION_PROGRAM_IDS)("rejects invalid canonical source %s even with a matching artifact", async id => {
    sources[id] = 'WLS-COLLECTION/1\nNOT_AN_INSTRUCTION ["value"]\nRETURN ["value"]\n';
    await put(`shared/wls-library/${COLLECTION_PROGRAM_FILES[id]}`, sources[id]);
    await putArtifact();
    const result = await checkWithoutWrites();
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("CollectionVMError: Unknown collection instruction at line 2.");
    expect(result.stderr).not.toContain("WLS library artifact is stale.");
  });

  it("rejects a foreign source version even with a matching artifact", async () => {
    sources["string.contains"] = 'WLS-FOREIGN/1\nRETURN ["value"]\n';
    await put(`shared/wls-library/${COLLECTION_PROGRAM_FILES["string.contains"]}`, sources["string.contains"]);
    await putArtifact();
    const result = await checkWithoutWrites();
    expect(result.status).toBe(1);
    expect(result.stdout).toBe("");
    expect(result.stderr).toContain("CollectionVMError: Unsupported collection source version.");
  });
});
