import { readFile } from "node:fs/promises";
import { LIBRARY_PROGRAM_FILES, LIBRARY_PROGRAM_IDS } from "../shared/wls-library-catalogue";
import { compileLibraryProgram } from "../shared/wls-library-compiler";

export const collectionLibraryArtifactURL = new URL("../shared/wls-library-sources.generated.ts", import.meta.url);

/** Deterministic serialization only: no normalisation or second authored source. */
export async function renderCollectionLibraryArtifact(): Promise<string> {
  const sources: Record<string, string> = {};
  for (const id of LIBRARY_PROGRAM_IDS) {
    const source = await readFile(new URL(`../shared/wls-library/${LIBRARY_PROGRAM_FILES[id]}`, import.meta.url), "utf8");
    compileLibraryProgram(source);
    sources[id] = source;
  }
  return "// Generated by npm run generate:wls-library. DO NOT EDIT.\n" +
    "// Canonical programs: shared/wls-library/**/*.wls\n" +
    `export const COLLECTION_LIBRARY_SOURCES = Object.freeze(${JSON.stringify(sources, null, 2)} as const);\n`;
}
